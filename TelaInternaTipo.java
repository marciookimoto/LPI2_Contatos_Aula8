    void atualizaTabela() {

        TipoDAO tipoDAO = new TipoDAO();
        tipos = tipoDAO.listarTodos();

        modelo.setRowCount(0);

        for (Tipo c : tipos) {
            modelo.addRow(new Object[]{
                c.getNome(),
                c.getDescricao()
            });
        }
    }

