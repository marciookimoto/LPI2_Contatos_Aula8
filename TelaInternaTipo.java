    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
        if (txtNome.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Informe o nome da categoria.");
            return;
        }

        Tipo tipo = new Tipo(
                txtNome.getText(),
                txtDescricao.getText()
        );

        TipoDAO tipoDAO = new TipoDAO();
        tipoDAO.inserir(tipo);

        atualizaTabela();

        txtNome.setText("");
        txtDescricao.setText("");
        txtNome.requestFocus();

    }//GEN-LAST:event_btnAdicionarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        linhaEditando = tblTipos.getSelectedRow();

        if (linhaEditando == -1) {
            JOptionPane.showMessageDialog(this, "Selecione uma categoria.");
            return;
        }

        Tipo tipo = tipos.get(linhaEditando);

        txtNome.setText(tipo.getNome());
        txtDescricao.setText(tipo.getDescricao());

        btnSalvar.setEnabled(true);

    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        if (linhaEditando == -1) {
            return;
        }
        if (txtNome.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Informe o nome da categoria.");
            return;
        }
        Tipo tipo = tipos.get(linhaEditando);
        tipo.setNome(txtNome.getText());
        tipo.setDescricao(txtDescricao.getText());
        TipoDAO tipoDAO = new TipoDAO();
        tipoDAO.atualizar(tipo.getId(), tipo);
        atualizaTabela();
        txtNome.setText("");
        txtDescricao.setText("");

        linhaEditando = -1;
        btnSalvar.setEnabled(false);

        JOptionPane.showMessageDialog(this, "Tipo atualizado!");

    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linhaExcluir = tblTipos.getSelectedRow();
if (linhaExcluir == -1) {
    JOptionPane.showMessageDialog(this, "Selecione um tipo.");
    return;
}
int decisao = JOptionPane.showConfirmDialog(
    this,
    "Deseja realmente excluir este tipo?",
    "Confirmação",
    JOptionPane.YES_NO_OPTION
);
if (decisao == JOptionPane.YES_OPTION) {
    Tipo tipo = tipos.get(linhaExcluir);
    TipoDAO tipoDAO = new TipoDAO();
    tipoDAO.excluir(tipo.getId());
    atualizaTabela();
    txtNome.setText("");
    txtDescricao.setText("");
    linhaEditando = -1;
    btnSalvar.setEnabled(false);
}

    }//GEN-LAST:event_btnExcluirActionPerformed


