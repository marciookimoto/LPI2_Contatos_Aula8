    private void carregarTipos() {
    TipoDAO tipoDAO = new TipoDAO();
    ArrayList<Tipo> tipos = tipoDAO.listarTodos();

    DefaultComboBoxModel<Tipo> modelo = new DefaultComboBoxModel<>();

    for (Tipo tipo : tipos) {
        modelo.addElement(tipo);
    }

    cmbTipo.setModel((javax.swing.ComboBoxModel) modelo);
}

    
     void atualizaTabela() {
        PessoaDAO pessoaDAO = new PessoaDAO();
        pessoas = pessoaDAO.listarTodos();
        System.out.println(pessoas.size());
        modelo.setRowCount(0);
        for (Pessoa p : pessoas) {
            modelo.addRow(
                    new Object[]{
                        p.getNome(),
                        p.getDataNascimento(),
                        p.getTelefone(),
                        p.getEmail(),
                        p.getTipo()
                    }
            );
        }
        lblTotal.setText("Total de Contatos: " + pessoas.size());
    }


