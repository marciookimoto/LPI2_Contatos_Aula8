    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
        if (txtNome.getText().isEmpty() || txtDataNascimento.getText().isEmpty() || txtTelefone.getText().isEmpty() || txtEmail.getText().isEmpty()
                || (!radioEmail.isSelected() && !radioWhats.isSelected())) {

            JOptionPane.showMessageDialog(rootPane, "Preencha todos os campos", "Alerta", JOptionPane.ERROR_MESSAGE);
            return;

        }

        Tipo tipo;
        tipo = (Tipo) cmbTipo.getSelectedItem();
        String preferencia = "";
        if (radioWhats.isSelected()) {
            preferencia = "WhatsApp";
        } else if (radioEmail.isSelected()) {
            preferencia = "E-mail";
        }

        Pessoa p = new Pessoa(txtNome.getText(), txtDataNascimento.getText(), txtTelefone.getText(), txtEmail.getText(), tipo, preferencia);
        PessoaDAO pessoaDAO = new PessoaDAO();
        pessoaDAO.inserir(p);

        pessoas.add(p);

        txtNome.setText("");
        txtDataNascimento.setText("");
        txtTelefone.setText("");
        txtEmail.setText("");
        txtNome.requestFocus();
        atualizaTabela();
        JOptionPane.showMessageDialog(this, "Cadastro realizado!", "Sucesso",
                JOptionPane.INFORMATION_MESSAGE);

    }//GEN-LAST:event_btnAdicionarActionPerformed

    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        Pessoa p = pessoas.get(linhaEditando);
        p.setNome(txtNome.getText());
        p.setDataNascimento(txtDataNascimento.getText());
        p.setTelefone(txtTelefone.getText());
        p.setEmail(txtEmail.getText());
        p.setTipo((Tipo) cmbTipo.getSelectedItem());
        if (radioEmail.isSelected()) {
            p.setPreferencia(radioEmail.getText());
        } else {
            p.setPreferencia(radioWhats.getText());
        }
        PessoaDAO pessoaDAO = new PessoaDAO();
        pessoaDAO.atualizar(p.getId(), p);

        atualizaTabela();
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        linhaEditando = tblContatos.getSelectedRow();

        Pessoa p = pessoas.get(linhaEditando);
        txtNome.setText(p.getNome());
        txtDataNascimento.setText(p.getDataNascimento());
        txtTelefone.setText(p.getTelefone());
        txtEmail.setText(p.getEmail());
        cmbTipo.setSelectedItem(p.getTipo());
        if (p.getPreferencia().equals("Email")) {
            radioEmail.setSelected(true);
        } else {
            radioWhats.setSelected(true);
        }
        btnSalvar.setEnabled(true);
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linhaExcluir = tblContatos.getSelectedRow();
        int decisao = JOptionPane.showConfirmDialog(rootPane, "Deseja mesmo excluir?", "Confirmação", JOptionPane.YES_NO_OPTION);
        if (decisao == JOptionPane.YES_OPTION) {
            Pessoa p = pessoas.get(linhaExcluir);
            PessoaDAO pessoaDAO = new PessoaDAO();
            pessoaDAO.excluir(p.getId());
            atualizaTabela();
        }

    }//GEN-LAST:event_btnExcluirActionPerformed


